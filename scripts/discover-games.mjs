// Game auto-discovery: every game folder registers itself through its own manifest.
// - React games:    packages/games/src/<id>/manifest.json (+ index.ts default export)
// - Embedded games: games/<id>/manifest.json (scored) or games/<id>/preview.json (Explore)
// Build, checks and the catalog all read this list; shared files never name a game.
// Running this file writes the gitignored *.generated.ts modules the catalog imports.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REACT_DIR = join(root, "packages/games/src");
const EMBEDDED_DIR = join(root, "games");
/** Shared, non-game folders that may sit next to games. */
const NOT_GAMES = new Set(["kit"]);

const folders = (dir) =>
  readdirSync(dir)
    .filter((name) => !NOT_GAMES.has(name) && !name.startsWith(".") && !name.startsWith("_"))
    .filter((name) => statSync(join(dir, name)).isDirectory())
    .sort();

/** @returns {{ id: string, dir: string, runtime: "react" | "embedded", mode: "learn" | "explore", manifestPath: string, manifest: Record<string, unknown> }[]} */
export function discoverGames() {
  const games = [];
  for (const id of folders(REACT_DIR)) {
    const dir = join(REACT_DIR, id);
    const manifestPath = join(dir, "manifest.json");
    if (!existsSync(manifestPath)) throw new Error(`React game folder without manifest: ${dir}`);
    games.push({ id, dir, runtime: "react", mode: "learn", manifestPath });
  }
  for (const id of folders(EMBEDDED_DIR)) {
    const dir = join(EMBEDDED_DIR, id);
    const manifest = join(dir, "manifest.json");
    const preview = join(dir, "preview.json");
    if (existsSync(manifest) === existsSync(preview))
      throw new Error(
        `${dir} needs exactly one of manifest.json (scored) or preview.json (Explore)`,
      );
    const explore = existsSync(preview);
    games.push({
      id,
      dir,
      runtime: "embedded",
      mode: explore ? "explore" : "learn",
      manifestPath: explore ? preview : manifest,
    });
  }
  return games.map((game) => {
    const manifest = JSON.parse(readFileSync(game.manifestPath, "utf8"));
    if (manifest.id !== game.id)
      throw new Error(`Folder ${relative(root, game.dir)} declares id "${manifest.id}"`);
    return { ...game, manifest };
  });
}

function importPath(from, to) {
  const path = relative(dirname(from), to).replaceAll("\\", "/");
  return path.startsWith(".") ? path : `./${path}`;
}

const HEADER = "// Generated by scripts/discover-games.mjs; gitignored. Do not edit.\n";

function write(path, text) {
  if (existsSync(path) && readFileSync(path, "utf8") === text) return;
  writeFileSync(path, text);
}

export function writeGeneratedModules(games = discoverGames()) {
  const catalogFile = join(root, "packages/game-catalog/src/discovered.generated.ts");
  const learn = games.filter((game) => game.mode === "learn");
  const explore = games.filter((game) => game.mode === "explore");
  const imports = [...learn, ...explore].map(
    (game, index) =>
      `import g${index} from "${importPath(catalogFile, game.manifestPath)}" with { type: "json" };`,
  );
  const names = (from, count) => Array.from({ length: count }, (_, i) => `g${from + i}`).join(", ");
  write(
    catalogFile,
    `${HEADER}${imports.join("\n")}\n\n/** Scored manifests, React games first, then embedded, each by id. */\nexport const discoveredManifests: readonly unknown[] = [${names(0, learn.length)}];\n/** Explore previews by id. */\nexport const discoveredPreviews: readonly unknown[] = [${names(learn.length, explore.length)}];\n`,
  );

  const registryFile = join(root, "packages/games/src/react-games.generated.ts");
  const react = games.filter((game) => game.runtime === "react");
  write(
    registryFile,
    `${HEADER}import type { GameDefinition } from "./kit";\n${react
      .map((game, index) => `import r${index} from "./${game.id}";`)
      .join(
        "\n",
      )}\n\n/** Each React game folder default-exports its GameDefinition. */\nexport const discoveredReactGames: readonly GameDefinition[] = [${react
      .map((_, index) => `r${index}`)
      .join(", ")}];\n`,
  );
  return games;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const games = writeGeneratedModules();
  const count = (mode) => games.filter((game) => game.mode === mode).length;
  console.log(`Discovered ${count("learn")} learning games and ${count("explore")} previews`);
}
